-- Reporting corrections and immutable Excel versions retain source and approval provenance.
alter table case_reporting_supplement_request
    add column request_kind varchar(16) not null default 'FILL' check (request_kind in ('FILL','CORRECT')),
    add column base_request_id bigint references case_reporting_supplement_request(id),
    add check ((request_kind='FILL' and base_request_id is null)
            or (request_kind='CORRECT' and base_request_id is not null));

create or replace function preserve_case_reporting_supplement_request() returns trigger language plpgsql as $$
begin
    if tg_op='DELETE' then raise exception 'Reporting supplement history cannot be deleted'; end if;
    if row(new.case_id,new.requested_values,new.original_values,new.effective_values,new.source_snapshot,
           new.reason,new.source_reference,new.requested_by,new.requested_username,new.requested_name,
           new.requester_dept_id,new.requester_category,new.requested_at,new.request_kind,new.base_request_id)
       is distinct from
       row(old.case_id,old.requested_values,old.original_values,old.effective_values,old.source_snapshot,
           old.reason,old.source_reference,old.requested_by,old.requested_username,old.requested_name,
           old.requester_dept_id,old.requester_category,old.requested_at,old.request_kind,old.base_request_id) then
        raise exception 'Reporting supplement request content is immutable';
    end if;
    if old.status<>'PENDING' or new.status not in ('APPROVED','REJECTED','CANCELLED') then
        raise exception 'Reporting supplement request was already processed';
    end if;
    return new;
end;
$$;

create function case_reporting_facts_at(p_known_at timestamptz default current_timestamp)
returns table(case_id bigint,institution_code varchar,institution_ownership varchar,institution_grade varchar,
    party_credit_no varchar,confirmed_violation_start date,confirmed_violation_end date,
    confirmed_violation_facts text,confirmed_violation_amount numeric,penalty_basis text,
    has_approved_supplement boolean)
language sql stable as $$
select c.id,
       case when coalesce(c.institution_code,'') ~ '[^[:space:]]' then c.institution_code
            when c.party_type='PROVIDER' then s.values->>'institutionCode' end::varchar,
       coalesce(c.institution_ownership,case when c.party_type='PROVIDER' then s.values->>'institutionOwnership' end)::varchar,
       coalesce(c.institution_grade,case when c.party_type='PROVIDER' then s.values->>'institutionGrade' end)::varchar,
       case when coalesce(c.party_credit_no,'') ~ '[^[:space:]]' then c.party_credit_no
            when c.party_type='INDIVIDUAL' then s.values->>'partyCreditNo' end::varchar,
       coalesce(c.confirmed_violation_start,(s.values->>'confirmedViolationStart')::date),
       coalesce(c.confirmed_violation_end,(s.values->>'confirmedViolationEnd')::date),
       case when coalesce(c.confirmed_violation_facts,'') ~ '[^[:space:]]' then c.confirmed_violation_facts
            else s.values->>'confirmedViolationFacts' end,
       coalesce(c.confirmed_violation_amount,(s.values->>'confirmedViolationAmount')::numeric),
       case when coalesce(d.penalty_basis,'') ~ '[^[:space:]]' then d.penalty_basis
            else s.values->>'penaltyBasis' end,
       s.values is not null
from case_file c left join case_decision d on d.case_id=c.id
left join lateral (
    select jsonb_object_agg(e.key,e.value order by r.reviewed_at,r.id) as values
    from case_reporting_supplement_request r cross join lateral jsonb_each(r.requested_values) e
    where r.case_id=c.id and r.status='APPROVED' and r.reviewed_at<=p_known_at
) s on true;
$$;

drop view case_reporting_facts;
create view case_reporting_facts as select * from case_reporting_facts_at();

create table report_frozen_batch (
    id bigint generated by default as identity primary key,
    request_key uuid not null,
    report_type varchar(24) not null check (report_type in ('PENALTIES','ENFORCEMENT_WORK','INTERVIEWS')),
    status varchar(16) not null default 'GENERATED' check (status in ('GENERATED','CONFIRMED')),
    period_start date not null,
    period_end date not null,
    business_cutoff date not null,
    known_at timestamptz not null,
    criteria jsonb not null,
    template_version varchar(80) not null,
    template_sha256 varchar(64) not null,
    rule_version varchar(80) not null,
    filename varchar(200) not null,
    workbook bytea not null check (octet_length(workbook)>0 and octet_length(workbook)<=25165824),
    file_sha256 varchar(64) not null check(file_sha256 ~ '^[0-9a-f]{64}$'),
    row_count integer not null check(row_count between 0 and 25000),
    parent_batch_id bigint references report_frozen_batch(id),
    generated_by bigint not null references sys_user(id),
    generated_username varchar(64) not null,
    generator_dept_id bigint references sys_dept(id),
    generated_at timestamptz not null default current_timestamp,
    confirmed_by bigint references sys_user(id),
    confirmed_username varchar(64),
    confirmer_dept_id bigint references sys_dept(id),
    confirmed_at timestamptz,
    confirmation_note varchar(2000),
    unique(generated_by,request_key),
    check(period_start<=period_end and period_end<=business_cutoff),
    check(parent_batch_id is null or parent_batch_id<>id),
    check((status='GENERATED' and num_nonnulls(confirmed_by,confirmed_username,confirmed_at,confirmation_note)=0)
       or (status='CONFIRMED' and num_nonnulls(confirmed_by,confirmed_username,confirmed_at,confirmation_note)=4
           and confirmed_by<>generated_by))
);
create index idx_report_frozen_batch_list on report_frozen_batch(report_type,id desc);

create table report_frozen_row (
    batch_id bigint not null references report_frozen_batch(id),
    row_key varchar(128) not null,
    source_type varchar(24) not null,
    source_id bigint not null,
    source_number varchar(128),
    sheet_index integer not null check(sheet_index>=0),
    row_number integer not null check(row_number>=4),
    cells jsonb not null check(jsonb_typeof(cells)='array'),
    cells_sha256 varchar(64) not null,
    primary key(batch_id,row_key)
);
create index idx_report_frozen_row_order on report_frozen_row(batch_id,sheet_index,row_number);

create function preserve_report_frozen_batch() returns trigger language plpgsql as $$
begin
    if tg_op='DELETE' then raise exception 'Frozen report cannot be deleted'; end if;
    if row(new.request_key,new.report_type,new.period_start,new.period_end,new.business_cutoff,new.known_at,new.criteria,
           new.template_version,new.template_sha256,new.rule_version,new.filename,new.workbook,new.file_sha256,
           new.row_count,new.parent_batch_id,new.generated_by,new.generated_username,new.generator_dept_id,new.generated_at)
       is distinct from
       row(old.request_key,old.report_type,old.period_start,old.period_end,old.business_cutoff,old.known_at,old.criteria,
           old.template_version,old.template_sha256,old.rule_version,old.filename,old.workbook,old.file_sha256,
           old.row_count,old.parent_batch_id,old.generated_by,old.generated_username,old.generator_dept_id,old.generated_at)
       or old.status<>'GENERATED' or new.status<>'CONFIRMED' then
        raise exception 'Frozen report bytes and generation facts are immutable';
    end if;
    return new;
end;
$$;
create trigger trg_preserve_report_frozen_batch before update or delete on report_frozen_batch
for each row execute function preserve_report_frozen_batch();

create function preserve_report_frozen_row() returns trigger language plpgsql as $$
begin
    raise exception 'Frozen report rows are immutable';
end;
$$;
create trigger trg_preserve_report_frozen_row before update or delete on report_frozen_row
for each row execute function preserve_report_frozen_row();
