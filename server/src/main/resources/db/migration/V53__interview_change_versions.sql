create table interview_change_request (
 id bigint generated by default as identity primary key,
 interview_id bigint not null references department_interview(id),
 request_key uuid not null,
 request_kind varchar(16) not null check(request_kind in ('CORRECT','VOID')),
 proposed_values jsonb not null,
 source_snapshot jsonb not null,
 reason varchar(2000) not null,
 source_reference varchar(1000) not null,
 requested_by bigint not null references sys_user(id),
 requested_username varchar(64) not null,
 requester_dept_id bigint not null references sys_dept(id),
 requester_category varchar(16) not null,
 requested_at timestamptz not null default clock_timestamp(),
 status varchar(16) not null default 'PENDING' check(status in ('PENDING','APPROVED','REJECTED','CANCELLED')),
 reviewed_by bigint references sys_user(id), reviewed_username varchar(64),
 reviewed_at timestamptz, opinion varchar(2000),
 unique(requested_by,request_key),
 check(status='PENDING' or num_nonnulls(reviewed_by,reviewed_username,reviewed_at,opinion)=4),
 check(status<>'APPROVED' or reviewed_by<>requested_by)
);
create unique index interview_change_one_pending on interview_change_request(interview_id) where status='PENDING';
create index interview_change_history on interview_change_request(interview_id,id desc);
create function preserve_interview_change_request() returns trigger language plpgsql as $$
begin
 if tg_op='DELETE' then raise exception 'Interview change history is immutable'; end if;
 if (to_jsonb(new)-array['status','reviewed_by','reviewed_username','reviewed_at','opinion'])
    is distinct from (to_jsonb(old)-array['status','reviewed_by','reviewed_username','reviewed_at','opinion'])
    or old.status<>'PENDING' or new.status not in ('APPROVED','REJECTED','CANCELLED') then
   raise exception 'Interview change request cannot be overwritten';
 end if;
 return new;
end $$;
create trigger interview_change_preserve before update or delete on interview_change_request
 for each row execute function preserve_interview_change_request();

create function effective_department_interviews(p_known_at timestamptz default current_timestamp)
returns table(id bigint,dept_id bigint,department_name varchar,institution_code varchar,institution_name varchar,
 interview_type varchar,reason varchar,content text,participants varchar,interview_date date,
 created_by bigint,source_agreement_id bigint,source_agency_cycle integer,change_id bigint)
language sql stable as $$
 select i.id,i.dept_id,i.department_name,
   coalesce(r.proposed_values->>'institutionCode',i.institution_code)::varchar,
   coalesce(r.proposed_values->>'institutionName',i.institution_name)::varchar,
   coalesce(r.proposed_values->>'interviewType',i.interview_type)::varchar,
   coalesce(r.proposed_values->>'reason',i.reason)::varchar,
   coalesce(r.proposed_values->>'content',i.content),
   coalesce(r.proposed_values->>'participants',i.participants)::varchar,
   coalesce((r.proposed_values->>'interviewDate')::date,i.interview_date),
   i.created_by,i.source_agreement_id,i.source_agency_cycle,r.id
 from department_interview i left join lateral (
   select * from interview_change_request c where c.interview_id=i.id and c.status='APPROVED'
      and c.reviewed_at<=p_known_at order by c.id desc limit 1
 ) r on true where r.id is null or r.request_kind<>'VOID';
$$;
