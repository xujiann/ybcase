-- Reporting supplements are separate from legal case facts, decisions and archived materials.
create table case_reporting_supplement_request (
    id bigint generated by default as identity primary key,
    case_id bigint not null references case_file(id),
    status varchar(16) not null default 'PENDING' check (status in ('PENDING','APPROVED','REJECTED','CANCELLED')),
    requested_values jsonb not null,
    original_values jsonb not null,
    effective_values jsonb not null,
    source_snapshot jsonb not null,
    reason varchar(512) not null,
    source_reference varchar(1000) not null,
    requested_by bigint not null references sys_user(id),
    requested_username varchar(64) not null,
    requested_name varchar(64) not null,
    requester_dept_id bigint references sys_dept(id),
    requester_category varchar(16),
    requested_at timestamptz not null default now(),
    reviewed_by bigint references sys_user(id),
    reviewed_username varchar(64),
    reviewed_name varchar(64),
    reviewer_dept_id bigint references sys_dept(id),
    reviewed_at timestamptz,
    opinion varchar(2000),
    approved_values jsonb,
    unique (id, case_id),
    check ((status='PENDING' and num_nonnulls(reviewed_by,reviewed_username,reviewed_name,reviewed_at,opinion,approved_values)=0)
        or (status in ('REJECTED','CANCELLED') and num_nonnulls(reviewed_by,reviewed_username,reviewed_name,reviewed_at,opinion)=5
            and approved_values is null)
        or (status='APPROVED' and num_nonnulls(reviewed_by,reviewed_username,reviewed_name,reviewed_at,opinion,approved_values)=6)),
    check (status <> 'APPROVED' or requested_by <> reviewed_by)
);
create unique index idx_case_reporting_supplement_pending on case_reporting_supplement_request(case_id) where status='PENDING';
create index idx_case_reporting_supplement_history on case_reporting_supplement_request(case_id,id desc);
create index idx_case_reporting_supplement_queue on case_reporting_supplement_request(id desc) where status='PENDING';

create function preserve_case_reporting_supplement_request() returns trigger language plpgsql as $$
begin
    if tg_op = 'DELETE' then
        raise exception 'Reporting supplement history cannot be deleted';
    end if;
    if row(new.case_id,new.requested_values,new.original_values,new.effective_values,new.source_snapshot,
           new.reason,new.source_reference,new.requested_by,new.requested_username,new.requested_name,
           new.requester_dept_id,new.requester_category,new.requested_at)
       is distinct from
       row(old.case_id,old.requested_values,old.original_values,old.effective_values,old.source_snapshot,
           old.reason,old.source_reference,old.requested_by,old.requested_username,old.requested_name,
           old.requester_dept_id,old.requester_category,old.requested_at) then
        raise exception 'Reporting supplement request content is immutable';
    end if;
    if old.status <> 'PENDING' or new.status not in ('APPROVED','REJECTED','CANCELLED') then
        raise exception 'Reporting supplement request was already processed';
    end if;
    return new;
end;
$$;
create trigger trg_preserve_case_reporting_supplement_request
    before update or delete on case_reporting_supplement_request
    for each row execute function preserve_case_reporting_supplement_request();

create table case_reporting_supplement_values (
    case_id bigint primary key references case_file(id),
    institution_code varchar(64) check (institution_code ~ '[^[:space:]]'),
    institution_ownership varchar(16) check (institution_ownership in ('PUBLIC','SOCIAL')),
    institution_grade varchar(16) check (institution_grade in ('TERTIARY','SECONDARY','PRIMARY','UNGRADED')),
    party_credit_no varchar(64) check (party_credit_no ~ '[^[:space:]]'),
    confirmed_violation_start date,
    confirmed_violation_end date,
    confirmed_violation_facts text check (confirmed_violation_facts ~ '[^[:space:]]'),
    confirmed_violation_amount numeric(14,2) check (confirmed_violation_amount >= 0),
    penalty_basis text check (penalty_basis ~ '[^[:space:]]'),
    approved_request_id bigint not null,
    foreign key (approved_request_id,case_id) references case_reporting_supplement_request(id,case_id),
    check (confirmed_violation_start <= confirmed_violation_end)
);

create view case_reporting_facts as
select c.id as case_id,
       case when coalesce(c.institution_code,'') ~ '[^[:space:]]' then c.institution_code
            when c.party_type='PROVIDER' then s.institution_code end as institution_code,
       coalesce(c.institution_ownership, case when c.party_type='PROVIDER' then s.institution_ownership end) as institution_ownership,
       coalesce(c.institution_grade, case when c.party_type='PROVIDER' then s.institution_grade end) as institution_grade,
       case when coalesce(c.party_credit_no,'') ~ '[^[:space:]]' then c.party_credit_no
            when c.party_type='INDIVIDUAL' then s.party_credit_no end as party_credit_no,
       coalesce(c.confirmed_violation_start,s.confirmed_violation_start) as confirmed_violation_start,
       coalesce(c.confirmed_violation_end,s.confirmed_violation_end) as confirmed_violation_end,
       case when coalesce(c.confirmed_violation_facts,'') ~ '[^[:space:]]' then c.confirmed_violation_facts
            else s.confirmed_violation_facts end as confirmed_violation_facts,
       coalesce(c.confirmed_violation_amount,s.confirmed_violation_amount) as confirmed_violation_amount,
       case when coalesce(d.penalty_basis,'') ~ '[^[:space:]]' then d.penalty_basis
            else s.penalty_basis end as penalty_basis,
       (s.case_id is not null) as has_approved_supplement
from case_file c left join case_decision d on d.case_id=c.id
left join case_reporting_supplement_values s on s.case_id=c.id;
