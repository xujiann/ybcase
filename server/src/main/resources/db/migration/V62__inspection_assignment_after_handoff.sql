alter table inspection add column assigned_user_id bigint references sys_user(id);

create index idx_accepted_inspection_handoff on department_handoff(inspection_id,id desc)
    where inspection_id is not null and status='ACCEPTED';
create index idx_accepted_clue_handoff on department_handoff(clue_id)
    where clue_id is not null and status='ACCEPTED';

create table inspection_assignment (
    id bigint generated by default as identity primary key,
    inspection_id bigint not null references inspection(id),
    handoff_id bigint not null references department_handoff(id),
    department_id bigint not null references sys_dept(id),
    previous_user_id bigint references sys_user(id),
    assigned_user_id bigint not null references sys_user(id),
    assigned_by bigint not null references sys_user(id),
    reason varchar(512) not null,
    assigned_at timestamptz not null default now(),
    check (assigned_by <> assigned_user_id),
    check (previous_user_id is distinct from assigned_user_id)
);
create index idx_inspection_assignment_history on inspection_assignment(inspection_id,id desc);
