create table department_interview (
    id bigint generated by default as identity primary key,
    dept_id bigint not null references sys_dept(id),
    department_name varchar(64) not null,
    institution_code varchar(64) not null,
    institution_name varchar(128) not null,
    interview_type varchar(64) not null,
    reason varchar(1000) not null,
    content text not null,
    participants varchar(512) not null,
    interview_date date not null,
    created_by bigint not null references sys_user(id),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index department_interview_date_idx on department_interview(interview_date, id);

