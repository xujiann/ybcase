create table clue_assignment (
    id bigint generated by default as identity primary key,
    clue_id bigint not null references case_clue(id),
    handoff_id bigint not null references department_handoff(id),
    department_id bigint not null references sys_dept(id),
    previous_handler text,
    assigned_user_id bigint not null references sys_user(id),
    assigned_by bigint not null references sys_user(id),
    reason varchar(512) not null,
    assigned_at timestamptz not null default now(),
    check (assigned_by <> assigned_user_id)
);
create index idx_clue_assignment_handoff on clue_assignment(handoff_id);

alter table biz_approval
    add column withdrawn_at timestamptz,
    add column withdraw_reason varchar(512);
