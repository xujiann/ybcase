-- Keep frozen bytes/rows immutable while permitting explicit, audited terminal outcomes.
alter table report_frozen_batch drop constraint report_frozen_batch_status_check;
alter table report_frozen_batch add check(status in ('GENERATED','CONFIRMED','WITHDRAWN','REJECTED','VOIDED'));
do $$ declare n text; begin
 for n in select conname from pg_constraint where conrelid='report_frozen_batch'::regclass
   and contype='c' and pg_get_constraintdef(oid) like '%num_nonnulls(confirmed_by%' loop
   execute format('alter table report_frozen_batch drop constraint %I',n);
 end loop;
end $$;
alter table report_frozen_batch add check(
 (status='CONFIRMED' and num_nonnulls(confirmed_by,confirmed_username,confirmed_at,confirmation_note)=4 and confirmed_by<>generated_by)
 or (status in ('GENERATED','WITHDRAWN','REJECTED') and num_nonnulls(confirmed_by,confirmed_username,confirmed_at,confirmation_note)=0)
 or status='VOIDED');
create table report_batch_event (
 id bigint generated by default as identity primary key,
 batch_id bigint not null references report_frozen_batch(id),
 event_type varchar(16) not null check(event_type in ('WITHDRAW','RETURN','VOID')),
 previous_status varchar(16) not null, resulting_status varchar(16) not null,
 actor_id bigint not null references sys_user(id),actor_username varchar(64) not null,
 opinion varchar(2000) not null,created_at timestamptz not null default clock_timestamp(),
 unique(batch_id)
);
create function preserve_report_batch_event() returns trigger language plpgsql as $$
begin raise exception 'Report lifecycle events are immutable'; end $$;
create trigger report_batch_event_preserve before update or delete on report_batch_event
 for each row execute function preserve_report_batch_event();
create or replace function preserve_report_frozen_batch() returns trigger language plpgsql as $$
begin
 if tg_op='DELETE' then raise exception 'Frozen report cannot be deleted'; end if;
 if (to_jsonb(new)-array['status','confirmed_by','confirmed_username','confirmer_dept_id','confirmed_at','confirmation_note'])
    is distinct from (to_jsonb(old)-array['status','confirmed_by','confirmed_username','confirmer_dept_id','confirmed_at','confirmation_note']) then
   raise exception 'Frozen report bytes and generation facts are immutable';
 end if;
 if old.status='GENERATED' and new.status='CONFIRMED' then return new; end if;
 if old.status in ('GENERATED','CONFIRMED') and new.status in ('WITHDRAWN','REJECTED','VOIDED')
   and (to_jsonb(new)-'status')=(to_jsonb(old)-'status')
   and exists(select 1 from report_batch_event e where e.batch_id=old.id
       and e.previous_status=old.status and e.resulting_status=new.status) then return new; end if;
 raise exception 'Invalid frozen report lifecycle transition';
end $$;
