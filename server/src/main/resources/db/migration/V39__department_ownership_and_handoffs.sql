-- Do not backfill old pre-case rows from today's personnel directory: it does not prove their historical owner.
alter table case_clue add column owner_dept_id bigint references sys_dept(id);
alter table inspection add column owner_dept_id bigint references sys_dept(id);
alter table biz_approval add column applicant_dept_id bigint references sys_dept(id);

create index idx_clue_owner_dept on case_clue(owner_dept_id) where owner_dept_id is not null;
create index idx_inspection_owner_dept on inspection(owner_dept_id) where owner_dept_id is not null;
create index idx_pending_approval_dept on biz_approval(applicant_dept_id) where status='PENDING';

create table department_handoff (
    id bigint generated by default as identity primary key,
    clue_id bigint references case_clue(id),
    inspection_id bigint references inspection(id),
    case_id bigint references case_file(id),
    source_no varchar(64) not null,
    from_dept_id bigint references sys_dept(id),
    to_dept_id bigint not null references sys_dept(id),
    requested_by bigint not null references sys_user(id),
    reason varchar(512) not null,
    status varchar(16) not null default 'PENDING',
    requested_at timestamptz not null default now(),
    decided_by bigint references sys_user(id),
    decided_at timestamptz,
    opinion varchar(512),
    check (num_nonnulls(clue_id, inspection_id, case_id) = 1),
    check (from_dept_id is distinct from to_dept_id),
    check ((status='PENDING' and num_nonnulls(decided_by, decided_at, opinion)=0)
        or (status in ('ACCEPTED','REJECTED','CANCELLED') and num_nonnulls(decided_by, decided_at, opinion)=3))
);
create unique index idx_pending_clue_handoff on department_handoff(clue_id)
    where status='PENDING' and clue_id is not null;
create unique index idx_pending_inspection_handoff on department_handoff(inspection_id)
    where status='PENDING' and inspection_id is not null;
create unique index idx_pending_case_handoff on department_handoff(case_id)
    where status='PENDING' and case_id is not null;
create index idx_dept_handoff_from on department_handoff(from_dept_id, id desc);
create index idx_dept_handoff_to on department_handoff(to_dept_id, id desc);

